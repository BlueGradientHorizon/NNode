#!/bin/bash
# Build (and optionally upload) a loadable ELF module from examples/<app>/.
#
# Uses only shared root dirs: boards/<target>/ for Kconfig defaults,
# build-<target>/modules/<app>/ for output and generated config, and
# managed_components/ for the loader component (reused, never downloaded
# again). Nothing is generated inside examples/ except the committable
# dependencies.lock (same policy as the root one).
#
#   ./build.sh <target> <action> <app>
#
#   target  board in ../boards/<target>/ (e.g. esp32c3)
#   action  build|flash|clean
#   app     module in examples/<app>/ (e.g. blink)
#
# Modules are never flashed over serial: "flash" uploads the .app.elf to
# the board over HTTP (needs BOARD_IP) and runs it via /api/elf/run.
set -e
cd "$(dirname "$0")/.."

TARGET="$1"
ACTION="$2"
APP="$3"

usage() {
  echo "usage: $0 <target> <action> <app>" >&2
  echo "  target  board in boards/<target>/ (e.g. esp32c3)" >&2
  echo "  action  build|flash|clean" >&2
  echo "  app     module in examples/<app>/ (e.g. blink)" >&2
}

if [ -z "$TARGET" ] || [ -z "$ACTION" ] || [ -z "$APP" ]; then
  usage
  exit 1
fi

SRC="examples/$APP"
OUT="build-$TARGET/modules/$APP"
BOARD_DIR="boards/$TARGET"

if [ ! -d "$BOARD_DIR" ]; then
  echo "unknown target '$TARGET' (no $BOARD_DIR directory)" >&2
  exit 1
fi
if [ ! -d "$SRC" ]; then
  echo "unknown app '$APP' (no $SRC directory)" >&2
  exit 1
fi

# shellcheck disable=SC1091
if [ -n "${IDF_PATH:-}" ] && [ -f "$IDF_PATH/export.sh" ]; then
  . "$IDF_PATH/export.sh" > /dev/null
elif [ -f ~/esp-idf/export.sh ]; then
  . ~/esp-idf/export.sh > /dev/null
fi

BOARD_IP="${BOARD_IP:-}"

# Shared Kconfig base: root defaults + board defaults. The board partition
# filename is project-relative, but our project lives in examples/<app>/,
# so pin the absolute shared path in a generated override (inside the
# build dir, never in examples/).
basedefaults() {
  echo "$PWD/sdkconfig.defaults;$PWD/$BOARD_DIR/sdkconfig.defaults"
}

pin_partitions() {
  if [ -f "$BOARD_DIR/partitions.csv" ]; then
    cat > "$OUT/sdkconfig.defaults" <<EOF
# Generated by examples/build.sh: absolute path to the shared board file.
CONFIG_PARTITION_TABLE_CUSTOM_FILENAME="$PWD/$BOARD_DIR/partitions.csv"
EOF
  fi
}

# Reuse the loader component from the root managed_components.
EXTRA_LOADER="$PWD/managed_components/elf_loader $PWD/managed_components/espressif__cmake_utilities"

idf_bare() {
  idf.py -C "$SRC" -B "$OUT" \
    -D "SDKCONFIG=$PWD/$OUT/sdkconfig" \
    -D "EXTRA_COMPONENT_DIRS=$EXTRA_LOADER" \
    "$@"
}

idf_mod() {
  idf.py -C "$SRC" -B "$OUT" \
    -D "SDKCONFIG=$PWD/$OUT/sdkconfig" \
    -D "SDKCONFIG_DEFAULTS=$MODULE_DEFAULTS" \
    -D "EXTRA_COMPONENT_DIRS=$EXTRA_LOADER" \
    "$@"
}

build_module() {
  if [ ! -f "$OUT/sdkconfig" ]; then
    # Fresh configure in two steps: set-target refuses to fullclean a
    # directory it did not create, so target selection runs first on an
    # empty dir, then the shared defaults are applied on the real build.
    rm -rf "$OUT"
    MODULE_DEFAULTS=""
    idf_bare set-target "$TARGET"
    rm -f "$OUT/sdkconfig"
  fi
  MODULE_DEFAULTS="$(basedefaults)"
  pin_partitions
  if [ -f "$OUT/sdkconfig.defaults" ]; then
    MODULE_DEFAULTS="$MODULE_DEFAULTS;$PWD/$OUT/sdkconfig.defaults"
  fi
  idf_mod build
  ls -la "$OUT/$APP.app.elf"
}

api() { # api <method> <path> [file]
  if [ $# -eq 3 ]; then
    curl -s -m 30 -X "$1" --data-binary "@$3" "http://$BOARD_IP$2"
  else
    curl -s -m 30 -X "$1" "http://$BOARD_IP$2"
  fi
}

flash_module() {
  local r
  build_module
  if [ -z "$BOARD_IP" ]; then
    echo "module built: $OUT/$APP.app.elf"
    echo "set BOARD_IP and rerun, or upload by hand:"
    echo "  curl -X POST --data-binary @$OUT/$APP.app.elf \\"
    echo "    \"http://<board-ip>/api/files/upload?name=$APP.elf\""
    echo "  curl -X POST \"http://<board-ip>/api/elf/run?name=$APP.elf\""
    return 0
  fi
  echo "uploading $APP.elf to $BOARD_IP ..."
  r=$(api POST "/api/files/upload?name=$APP.elf" "$OUT/$APP.app.elf")
  echo "upload: $r"
  # Replace a running copy: stop/unload errors are fine when idle.
  r=$(api POST "/api/elf/stop?name=$APP.elf"); echo "stop: $r"
  r=$(api POST "/api/elf/unload?name=$APP.elf"); echo "unload: $r"
  r=$(api POST "/api/elf/run?name=$APP.elf"); echo "run: $r"
}

case "$ACTION" in
  build)
    build_module
    ;;
  flash)
    flash_module
    ;;
  clean)
    rm -rf "$OUT"
    ;;
  *)
    usage
    exit 1
    ;;
esac
